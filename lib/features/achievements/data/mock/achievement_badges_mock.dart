AchievementBadgeDto _badge({
  required int id,
  required String name,
  required String key,
  required String exerciseMetric,
  required int factionId,
  required String iconUrlKey,
  required String requirementTitle,
  required String description,
  int? progressId,
  int? tier,
}) {
  final displayedTier = tier ?? 1;

  return AchievementBadgeDto(
    id: id,
    name: name,
    key: key,
    exerciseMetric: exerciseMetric,
    factionId: factionId,
    iconUrlKey: iconUrlKey,
    requirementTitle: requirementTitle,
    description: description,
    isCompleted: tier != null,
    userProgress: tier == null
        ? null
        : UserProgressDto(
            id: progressId ?? id,
            tier: tier,
            key: key,
          ),
    iconUrl: '$_milestoneBucketUrl/$iconUrlKey-$displayedTier.svg',
  );
}
